/**
 * Green Agent fix branch (T-15, T-54).
 *
 * Applies patches onto a NEW branch cut from the scanned commit, in a
 * scratch clone so the runner's checkout is untouched, and returns what the
 * front end needs to push it and open a PR/MR.  This module never pushes,
 * never merges, and never targets the source branch.
 */
import { exec } from "../exec.js";
import { withTempDir } from "../fs/tmp.js";
import type { Logger } from "../log.js";
import type { FixPatch } from "./request.js";

export interface FixBranchPlan {
  branchName: string;
  baseSha: string;
  /** Patches that applied cleanly, in order. */
  applied: FixPatch[];
  rejected: Array<{ patch: FixPatch; reason: string }>;
  /** Path of the scratch clone holding the commit; valid until `cleanup()`. */
  repoDir: string;
  commitSha: string | null;
  cleanup(): Promise<void>;
}

export function fixBranchName(scanId: string, commitSha: string): string {
  const safeScan = scanId.replace(/[^A-Za-z0-9_-]/g, "").slice(0, 32) || "scan";
  return `nandee/fix-${safeScan}-${commitSha.slice(0, 8)}`;
}

export function commitMessage(applied: ReadonlyArray<FixPatch>, scanId: string, reportUrl: string): string {
  const lines = [
    `fix(security): apply ${applied.length} Nandee Green Agent patch${applied.length === 1 ? "" : "es"}`,
    "",
    ...applied.map((p) => `- ${p.finding.title.replace(/[\r\n]+/g, " ").slice(0, 100)} (${p.finding.severity})`),
    "",
    `Generated by Nandee from scan ${scanId}: ${reportUrl}`,
    "Review before merging: these changes were written by an AI agent.",
  ];
  return lines.join("\n");
}

/**
 * Builds the fix commit in a scratch clone of `sourceDir` at `baseSha`.
 * The caller pushes `branchName` from `repoDir` using its own credentials
 * and must call `cleanup()`.
 */
export async function buildFixBranch(sourceDir: string, baseSha: string, scanId: string, reportUrl: string, patches: ReadonlyArray<FixPatch>, log: Logger): Promise<FixBranchPlan> {
  const branchName = fixBranchName(scanId, baseSha);
  const { createTempDir } = await import("../fs/tmp.js");
  const tmp = await createTempDir("nandee-fix-");
  const repoDir = tmp.path;
  const git = (args: string[], stdin?: string) => exec("git", args, { cwd: repoDir, timeoutMs: 120_000, ...(stdin !== undefined ? { stdin } : {}) });

  try {
    // Local clone: no network, no credentials involved.
    const clone = await exec("git", ["clone", "--quiet", "--no-hardlinks", "--", sourceDir, repoDir], { cwd: sourceDir, timeoutMs: 300_000 });
    if (clone.code !== 0) throw new Error(`git clone failed: ${clone.stderr.slice(0, 500)}`);
    const co = await git(["checkout", "--quiet", "-b", branchName, baseSha]);
    if (co.code !== 0) throw new Error(`git checkout ${baseSha} failed: ${co.stderr.slice(0, 500)}`);
    await git(["config", "user.name", "Nandee Green Agent"]);
    await git(["config", "user.email", "green-agent@nandee.ai"]);

    const applied: FixPatch[] = [];
    const rejected: FixBranchPlan["rejected"] = [];
    for (const p of patches) {
      const check = await git(["apply", "--check", "--whitespace=nowarn", "-"], p.diff);
      if (check.code !== 0) {
        rejected.push({ patch: p, reason: `patch does not apply: ${check.stderr.slice(0, 200)}` });
        continue;
      }
      const touches = await git(["apply", "--numstat", "-"], p.diff);
      if (/(^|\n)\S+\t\S+\t(\.github\/|\.gitlab-ci|\.gitlab\/)/.test(touches.stdout)) {
        rejected.push({ patch: p, reason: "patch touches CI configuration; not applied automatically" });
        continue;
      }
      const apply = await git(["apply", "--index", "--whitespace=nowarn", "-"], p.diff);
      if (apply.code !== 0) {
        rejected.push({ patch: p, reason: `git apply failed: ${apply.stderr.slice(0, 200)}` });
        await git(["checkout", "--", "."]);
        continue;
      }
      applied.push(p);
    }

    let commitSha: string | null = null;
    if (applied.length) {
      const c = await git(["commit", "--quiet", "--no-verify", "-F", "-"], commitMessage(applied, scanId, reportUrl));
      if (c.code !== 0) throw new Error(`git commit failed: ${c.stderr.slice(0, 500)}`);
      commitSha = (await git(["rev-parse", "HEAD"])).stdout.trim();
    }
    log.info(`Green Agent: ${applied.length} patch(es) applied on ${branchName}, ${rejected.length} rejected`);
    return { branchName, baseSha, applied, rejected, repoDir, commitSha, cleanup: tmp.cleanup };
  } catch (err) {
    await tmp.cleanup();
    throw err;
  }
}

/** Convenience for callers that only need the plan and will push elsewhere. */
export async function withFixBranch<T>(args: Parameters<typeof buildFixBranch>, fn: (plan: FixBranchPlan) => Promise<T>): Promise<T> {
  return withTempDir(async () => {
    const plan = await buildFixBranch(...args);
    try {
      return await fn(plan);
    } finally {
      await plan.cleanup();
    }
  });
}
